const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync('src/config/mediaConfig.ts', 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const sandbox = {exports:{}};
vm.runInNewContext(compiled, sandbox);
const {migrateGallery, HOME_GALLERY} = sandbox.exports;
const defaults = HOME_GALLERY.map(x=>x.url);
const prefix = 'https://images.higgs.ai/?default=1&output=webp&url=https%3A%2F%2Fd8j0ntlcm91z4.cloudfront.net%2Fuser_38xzZboKViGWJOttwIXH07lWA1P%2Fhf_20260629_';
assert.equal(JSON.stringify(migrateGallery(undefined)),JSON.stringify(defaults));
assert.equal(JSON.stringify(migrateGallery(Array.from({length:10},(_,i)=>prefix+i))),JSON.stringify(defaults));
const custom = '/assets/custom-client.jpg';
assert.equal(migrateGallery([custom,prefix+'old'])[0],custom);
assert.equal(migrateGallery([custom,prefix+'old'])[1],defaults[1]);
assert.equal(JSON.stringify(migrateGallery(defaults)),JSON.stringify(defaults));
assert.equal(migrateGallery(['https://images.higgs.ai/custom.png'])[0],'https://images.higgs.ai/custom.png');
console.log('PASS: fresh, legacy, mixed custom, existing current gallery, unrelated CDN');
